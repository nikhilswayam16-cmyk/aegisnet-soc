"""Transparent, deterministic detection rules.

These rules are deliberately explainable: every alert can be traced to a rule,
threshold, event window and evidence records. They are a teaching baseline, not
a replacement for a production detection engineering program.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta

from sqlalchemy.orm import Session

from .models import IOC, Alert, AuditEntry, Event

FAILED_OUTCOMES = {"failure", "failed", "denied", "blocked"}
SUCCESS_OUTCOMES = {"success", "succeeded", "allowed", "ok"}


def utcnow_naive() -> datetime:
    """Return UTC as a naive value for consistent SQLite storage."""
    return datetime.now(UTC).replace(tzinfo=None)


def as_utc_naive(value: datetime) -> datetime:
    if value.tzinfo is None:
        return value
    return value.astimezone(UTC).replace(tzinfo=None)


def timestamp_text(value: datetime | None) -> str | None:
    if value is None:
        return None
    if value.tzinfo is None:
        value = value.replace(tzinfo=UTC)
    return value.astimezone(UTC).isoformat(timespec="seconds").replace("+00:00", "Z")


def shannon_entropy(value: str) -> float:
    if not value:
        return 0.0
    counts = {char: value.count(char) for char in set(value)}
    length = len(value)
    return -sum((count / length) * math.log2(count / length) for count in counts.values())


def event_evidence(event: Event) -> dict:
    return {
        "id": event.id,
        "event_uid": event.event_uid,
        "timestamp": timestamp_text(event.timestamp),
        "event_type": event.event_type,
        "source": event.source,
        "src_ip": event.src_ip,
        "dst_ip": event.dst_ip,
        "dst_port": event.dst_port,
        "username": event.username,
        "asset": event.asset,
        "action": event.action,
        "outcome": event.outcome,
        "domain": event.domain,
        "bytes_out": event.bytes_out,
        "process_name": event.process_name,
    }


@dataclass(frozen=True, slots=True)
class Finding:
    fingerprint: str
    rule_id: str
    title: str
    description: str
    severity: str
    risk_score: int
    mitre_technique: str | None
    mitre_tactic: str | None
    events: list[Event]
    src_ip: str | None = None
    asset: str | None = None
    username: str | None = None


def _emit(db: Session, finding: Finding) -> Alert:
    now = utcnow_naive()
    alert = db.query(Alert).filter(Alert.fingerprint == finding.fingerprint).one_or_none()
    incoming = [event_evidence(event) for event in finding.events]

    if alert is None:
        alert = Alert(
            fingerprint=finding.fingerprint,
            rule_id=finding.rule_id,
            title=finding.title,
            description=finding.description,
            severity=finding.severity,
            risk_score=finding.risk_score,
            status="open",
            src_ip=finding.src_ip,
            asset=finding.asset,
            username=finding.username,
            mitre_technique=finding.mitre_technique,
            mitre_tactic=finding.mitre_tactic,
            event_count=0,
            evidence_json="[]",
            first_seen=min((as_utc_naive(e.timestamp) for e in finding.events), default=now),
            last_seen=max((as_utc_naive(e.timestamp) for e in finding.events), default=now),
            created_at=now,
            updated_at=now,
        )
        db.add(alert)
        db.flush()
        db.add(
            AuditEntry(
                alert_id=alert.id,
                actor="detection-engine",
                action="alert-created",
                from_status=None,
                to_status="open",
                note=f"Generated by {finding.rule_id} from {len(finding.events)} evidence event(s).",
                created_at=now,
            )
        )
    else:
        known = json.loads(alert.evidence_json or "[]")
        known_ids = {item.get("id") for item in known}
        for item in incoming:
            if item.get("id") not in known_ids:
                known.append(item)
        alert.evidence_json = json.dumps(known[-100:])
        alert.event_count = len(known[-100:])
        alert.description = finding.description
        alert.severity = finding.severity
        alert.risk_score = finding.risk_score
        alert.asset = finding.asset or alert.asset
        alert.username = finding.username or alert.username
        alert.last_seen = max(alert.last_seen, max(as_utc_naive(e.timestamp) for e in finding.events))
        alert.updated_at = now
        # Preserve analyst ownership and workflow status unless the finding reappears
        # after resolution, in which case explicitly reopen it and record the change.
        if alert.status == "resolved":
            alert.status = "open"
            db.add(
                AuditEntry(
                    alert_id=alert.id,
                    actor="detection-engine",
                    action="alert-reopened",
                    from_status="resolved",
                    to_status="open",
                    note="A new matching event was observed after resolution.",
                    created_at=now,
                )
            )

    if alert.event_count == 0:
        alert.evidence_json = json.dumps(incoming[-100:])
        alert.event_count = len(incoming)
    return alert


class DetectionEngine:
    """Run the bounded set of detection rules against an ingested event."""

    def evaluate(self, db: Session, event: Event) -> list[Alert]:
        found: list[Alert] = []
        when = as_utc_naive(event.timestamp)

        # AUTH-001: repeated failed authentication from one source address.
        if event.event_type == "auth" and (event.outcome or "").lower() in FAILED_OUTCOMES and event.src_ip:
            window_start = when - timedelta(minutes=5)
            evidence = (
                db.query(Event)
                .filter(
                    Event.src_ip == event.src_ip,
                    Event.event_type == "auth",
                    Event.timestamp >= window_start,
                    Event.timestamp <= when,
                )
                .order_by(Event.timestamp.asc())
                .all()
            )
            failures = [e for e in evidence if (e.outcome or "").lower() in FAILED_OUTCOMES]
            if len(failures) >= 5:
                found.append(
                    _emit(
                        db,
                        Finding(
                            fingerprint=f"auth-bruteforce:{event.src_ip}",
                            rule_id="AUTH-001",
                            title="Possible password brute-force activity",
                            description=(
                                f"Observed {len(failures)} failed authentication attempts from "
                                f"{event.src_ip} within five minutes. Review the source, targeted "
                                "accounts and authentication policy before containment."
                            ),
                            severity="high",
                            risk_score=86,
                            mitre_technique="T1110",
                            mitre_tactic="Credential Access",
                            events=failures,
                            src_ip=event.src_ip,
                            asset=event.asset,
                            username=event.username,
                        ),
                    )
                )

        # NET-001: broad destination-port fan-out in a short time window.
        if event.event_type == "network" and event.src_ip and event.dst_port:
            window_start = when - timedelta(seconds=60)
            recent = (
                db.query(Event)
                .filter(
                    Event.src_ip == event.src_ip,
                    Event.event_type == "network",
                    Event.timestamp >= window_start,
                    Event.timestamp <= when,
                    Event.dst_port.is_not(None),
                )
                .order_by(Event.timestamp.asc())
                .all()
            )
            ports = {item.dst_port for item in recent if item.dst_port is not None}
            if len(ports) >= 8:
                found.append(
                    _emit(
                        db,
                        Finding(
                            fingerprint=f"network-port-scan:{event.src_ip}",
                            rule_id="NET-001",
                            title="Possible network port scan",
                            description=(
                                f"Source {event.src_ip} contacted {len(ports)} distinct destination "
                                "ports within 60 seconds. Confirm whether this is authorized discovery."
                            ),
                            severity="medium",
                            risk_score=72,
                            mitre_technique="T1046",
                            mitre_tactic="Discovery",
                            events=recent,
                            src_ip=event.src_ip,
                            asset=event.asset,
                        ),
                    )
                )

        # THREAT-001: exact local IOC match. No external feed is contacted.
        candidates = [("ip", event.src_ip), ("ip", event.dst_ip), ("domain", event.domain), ("sha256", event.hash_sha256)]
        for kind, indicator in candidates:
            if not indicator:
                continue
            ioc = (
                db.query(IOC)
                .filter(IOC.kind == kind, IOC.indicator == indicator.lower())
                .one_or_none()
            )
            if ioc is not None:
                found.append(
                    _emit(
                        db,
                        Finding(
                            fingerprint=f"ioc-match:{kind}:{ioc.indicator}",
                            rule_id="THREAT-001",
                            title=f"Threat-intelligence match: {ioc.indicator}",
                            description=(
                                f"Event matched a local {kind} indicator classified as "
                                f"'{ioc.threat_type}' by {ioc.source} (confidence {ioc.confidence}/100). "
                                "Validate context and scope before taking action."
                            ),
                            severity="critical" if ioc.confidence >= 90 else "high",
                            risk_score=min(99, 70 + ioc.confidence // 3),
                            mitre_technique="T1071" if kind == "domain" else "T1105",
                            mitre_tactic="Command and Control",
                            events=[event],
                            src_ip=event.src_ip,
                            asset=event.asset,
                            username=event.username,
                        ),
                    )
                )

        # EXFIL-001: unusually large single outbound transfer.
        if event.bytes_out >= 10 * 1024 * 1024:
            found.append(
                _emit(
                    db,
                    Finding(
                        fingerprint=f"large-egress:{event.asset or event.src_ip or 'unknown'}",
                        rule_id="EXFIL-001",
                        title="Unusually large outbound data transfer",
                        description=(
                            f"A single event reported {event.bytes_out / (1024 * 1024):.1f} MiB sent "
                            "outbound, above the 10 MiB demonstration threshold. Compare with the "
                            "asset's normal workload and approved transfer windows."
                        ),
                        severity="high",
                        risk_score=84,
                        mitre_technique="T1567",
                        mitre_tactic="Exfiltration",
                        events=[event],
                        src_ip=event.src_ip,
                        asset=event.asset,
                        username=event.username,
                    ),
                )
            )

        # EDR-001: successful privileged action from an endpoint event.
        if (
            event.event_type == "endpoint"
            and (event.outcome or "").lower() in SUCCESS_OUTCOMES
            and (
                (event.action or "").lower() in {"privilege_escalation", "sudo", "privileged_execution"}
                or (event.process_name or "").lower() in {"sudo", "runas"}
            )
        ):
            found.append(
                _emit(
                    db,
                    Finding(
                        fingerprint=f"privileged-action:{event.asset or event.src_ip or 'unknown'}:{event.username or 'unknown'}",
                        rule_id="EDR-001",
                        title="Successful privileged execution observed",
                        description=(
                            "An endpoint telemetry event indicates successful privileged execution. "
                            "Confirm the initiating user, command, change ticket and process ancestry."
                        ),
                        severity="medium",
                        risk_score=68,
                        mitre_technique="T1548.003",
                        mitre_tactic="Privilege Escalation",
                        events=[event],
                        src_ip=event.src_ip,
                        asset=event.asset,
                        username=event.username,
                    ),
                )
            )

        # DNS-001: high-entropy, long labels can be a DGA/tunnelling signal.
        if event.event_type == "dns" and event.domain:
            label = event.domain.split(".")[0]
            entropy = shannon_entropy(label)
            if len(label) >= 28 and entropy >= 3.6:
                found.append(
                    _emit(
                        db,
                        Finding(
                            fingerprint=f"dns-high-entropy:{event.domain}",
                            rule_id="DNS-001",
                            title="High-entropy DNS query observed",
                            description=(
                                f"The queried label has length {len(label)} and Shannon entropy "
                                f"{entropy:.2f} bits/character. This heuristic can flag DGA-like "
                                "domains; it is not proof of malicious activity."
                            ),
                            severity="medium",
                            risk_score=65,
                            mitre_technique="T1568.002",
                            mitre_tactic="Command and Control",
                            events=[event],
                            src_ip=event.src_ip,
                            asset=event.asset,
                        ),
                    )
                )

        return found
